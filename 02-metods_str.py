# Metodos de los Strings (str)

palabra = "Hola Mundo"

print(palabra[5])

# lower()
print(palabra.lower())

# upper()
print(palabra.upper())

# capitalize
nombre = 'sebastian'
print(nombre.capitalize())

# split
planeta = 'Saturno-Venus-Urano'
print(planeta.split())

# replace
saludo = 'hola Sebastian'
print(saludo.replace("Sebastian", "Andres"))
